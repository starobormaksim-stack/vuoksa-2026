--  3. RLS: читать может любой, писать напрямую — НИКТО, убирать — владелец.
--
--  ⚠️ Снести ВСЕ прежние политики обязательно. 04.08.2026 первое применение
--  пути Б защиту не дало: RLS включился, функция заработала, а прямая запись
--  осталась открытой — на таблице висела старая разрешающая политика (такие
--  Supabase заводит сам, когда RLS включают кнопкой в интерфейсе). Одна такая
--  политика сводит всю защиту на нет, поэтому список чистится целиком.
-- ───────────────────────────────────────────────────────────────────────────

alter table public.trips enable row level security;

do $$
declare прежняя record;
begin
  for прежняя in
    select policyname from pg_policies where schemaname = 'public' and tablename = 'trips'
  loop
    execute format('drop policy %I on public.trips', прежняя.policyname);
  end loop;
end $$;

create policy "читать может любой"
  on public.trips for select
  using (true);

/* Строку песочницы надо уметь убирать после проверок, иначе она копится.
   Боевые строки это не затрагивает: условие ловит только имена на «-test». */
create policy "песочницу можно убирать"
  on public.trips for delete
  using (id like '%-test');

/* Свою поездку убирает тот, чья почта записана в owner_email, — и только он.
   Чужая почта, пустой owner_email и незалогиненный посетитель не убирают ничего.

   Строка vuoksa2026 защищена отдельно и намеренно: это лист, ради которого всё
   и затевалось, он открывается по короткому адресу, и терять его по нечаянному
   нажатию нельзя. Если он когда-нибудь действительно станет не нужен — убрать
   его можно здесь же, в SQL Editor, одной строкой:
       delete from public.trips where id = 'vuoksa2026';
   Приложение такой поездки удалить не даст ни при каких правах. */
create policy "свою поездку убирает её владелец"
  on public.trips for delete
  to authenticated
  using (
    id <> 'vuoksa2026'
    and coalesce(owner_email, '') <> ''
    and lower(owner_email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );

-- ───────────────────────────────────────────────────────────────────────────
--  4. Проверка. Должно быть: «защита включена» = true; ровно ТРИ политики —
--     одна SELECT и две DELETE (ни одной на INSERT или UPDATE); колонка
--     owner_email на месте (третий запрос вернёт одну строку).
-- ───────────────────────────────────────────────────────────────────────────

select relrowsecurity as "защита включена" from pg_class where relname = 'trips';
select policyname as "политика", cmd as "на что" from pg_policies where tablename = 'trips';
select column_name as "колонка владельца есть"
  from information_schema.columns
 where table_schema = 'public' and table_name = 'trips' and column_name = 'owner_email';

-- Полезно посмотреть, какие поездки уже есть и за кем они закреплены:
select id as "поездка",
       coalesce(owner_email, '— ничья —') as "владелец",
       updated_at as "последняя правка"
  from public.trips
 order by updated_at desc;

