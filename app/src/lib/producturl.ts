/**
 * Ссылка на страницу товара у позиции «Сборов» и «Закупки».
 *
 * Требование заказчика 05.08.2026: «условно, я туда либо вписываю название товара,
 * либо вставляю ссылку». Орган ввода один — то же поле названия, которое уже есть
 * в строке (постулаты 1 и 6). Значит кто-то должен отличать одно от другого, и это
 * место — здесь, а не в двух разделах по отдельности.
 *
 * ⚠️ Ссылка — это чужой адрес в нашем интерфейсе. Отсюда три правила, и все три
 * держатся именно здесь:
 *   1. принимаем ТОЛЬКО http и https — `javascript:` в поле названия не должно
 *      превращаться в нажимаемую ссылку;
 *   2. показываем ИМЯ САЙТА, а не адрес целиком: адрес не читается и занимает
 *      всю строку таблицы;
 *   3. открываем с `rel="noopener noreferrer"` — это забота вызывающего, но
 *      напоминание живёт рядом с разбором.
 *
 * Снятия названия, фотографии и цены со страницы здесь нет и не будет: браузеру
 * чужую страницу читать запрещено (CORS), это часть Б и делается посредником
 * на сервере. Пока её нет, вставленный адрес всё равно сохраняется и нажимается —
 * слово заказчика: «но ссылку как минимум просто оставить можно будет».
 */

/**
 * Похоже ли введённое на адрес страницы.
 *
 * Нарочно строго: только то, что человек ЯВНО вставил как ссылку, то есть со
 * схемой. «5 л воды» ссылкой не станет никогда, и «alpindustria.ru» без схемы —
 * тоже: в поле названия куда чаще пишут словами, чем адресами, и ошибиться
 * в эту сторону дороже.
 */
export function looksLikeUrl(s: string): boolean {
  return /^https?:\/\/\S+$/i.test(s.trim())
}

/**
 * Привести введённое к адресу, который можно открыть, или вернуть пусто.
 * Пусто — значит это не ссылка, и обращаться с введённым надо как с названием.
 */
export function safeUrl(s: string): string {
  const raw = s.trim()
  if (!looksLikeUrl(raw)) return ''
  try {
    const u = new URL(raw)
    /* Пояс поверх подтяжек: схему уже проверило регулярное выражение, но список
       разрешённого должен стоять там, где его видно. */
    if (u.protocol !== 'http:' && u.protocol !== 'https:') return ''
    return u.toString()
  } catch {
    return ''
  }
}

/**
 * Имя сайта для показа: «alpindustria.ru». Это и подпись ссылки, и запасное
 * название позиции, если человек вставил адрес и ничего не написал словами.
 */
export function siteName(url: string): string {
  try {
    return new URL(url).hostname.replace(/^www\./i, '')
  } catch {
    return ''
  }
}

/** Позиция, у которой есть название и ссылка на товар: `Gear` и `Buy`. */
interface Named {
  n: string
  url?: string
  img?: string
  pat?: number
}

/**
 * Записать то, что человек ввёл в поле НАЗВАНИЯ. Один орган ввода на две вещи —
 * ровно как просил заказчик, — поэтому решение принимается здесь, а не в разделе.
 *
 * Обычный текст: название меняется, ссылка не трогается. Так позицию со ссылкой
 * можно переименовать своими словами, ничего не потеряв, — и именно это
 * произойдёт, когда часть Б подставит название со страницы, а человек его
 * поправит.
 *
 * Адрес: он уезжает в `url`, а названием становится имя сайта — но только если
 * своего названия ещё нет. Написанное человеком не затирается никогда: он вставлял
 * ссылку К позиции, а не ВМЕСТО неё.
 */
export function saveNameOrUrl(item: Named, typed: string): void {
  const url = safeUrl(typed)
  if (!url) {
    item.n = typed
    return
  }
  item.url = url
  /* Фотография и время снятия цены относятся к прежней ссылке — с новой они
     ничего общего не имеют. Заполнит их часть Б, когда прочитает страницу. */
  item.img = ''
  item.pat = 0
  if (!item.n.trim()) item.n = siteName(url)
}
