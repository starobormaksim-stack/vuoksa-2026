/**
 * Люди: порядок в списках и личная метка каждого.
 *
 * ─── Порядок ───
 * Человек, пришедший по своей ссылке, должен видеть СЕБЯ первым — во всех списках:
 * «Команда», «кто везёт», выбор покупателя, разбор готовности. Остальные идут дальше
 * в обычном порядке документа. Порядок самого документа (S.people) при этом не меняется:
 * это общая вещь, и переставлять её под каждого читателя нельзя.
 *
 * ─── Метка ───
 * Бренд — ровно четыре цвета (графит, хвоя, крем, янтарь), новых оттенков не заводим.
 * Поэтому люди различаются насыщенностью янтаря и РИСУНКОМ внутри метки.
 *
 * Правка 04.08.2026: снаружи метка у всех — кружок («пускай будут кружочки, но цвета
 * пускай будут на подложке, чтобы их было лучше видно»). Прежние квадрат и ромб убраны:
 * различие формой переехало ВНУТРЬ кружка, а сам кружок лёг на контрастную подложку
 * (см. components/flops/PersonMark.tsx). Требование WCAG 1.4.1 «различие не только
 * цветом» держит именно рисунок: при дальтонизме и в чёрно-белой печати оттенок
 * пропадает, а сплошной кружок, кольцо, половинка и точка остаются различимы.
 *
 * Разброс насыщенности стал уже, чем был (было 0,44…1). Причина: янтарь лежит теперь
 * на подложке цвета карточки, и бледный оттенок терял на ней контраст — 0,44 давало
 * 1,85 : 1 против кремовой подложки при нужных 3 : 1. В нижней границе 0,7 контраст
 * не опускается ниже 3 : 1 ни в светлой теме, ни в тёмной. Плата за это — люди почти
 * не различаются насыщенностью, различает их рисунок.
 *
 * Правка 04.08.2026, вторая: рисунков было четыре, и пятый человек в поездке получал
 * метку первого. Теперь их восемь. Порядок первых четырёх не тронут — у Макса, Кости,
 * Миши и Жени метка осталась прежней. Новые четыре подобраны так, чтобы читаться на
 * рабочем размере метки (14 px, поле под янтарь ≈ 10 px): четверть, две точки,
 * диагональная половинка, шахматка. Похожие пары разведены по списку подальше:
 * вертикальная половинка (3-я) и диагональная (7-я) стоят через четыре места, четверть
 * (5-я) и шахматка (8-я) — через три, поэтому соседи по списку не путаются.
 *
 * Насыщенность даёт восемь ступеней, но коридор у неё узкий (0,7…1 у метки), поэтому
 * ступени — только подспорье: людей разводит рисунок. У полос коридор шире, но и там
 * ниже 0,44 полоса на приглушённом фоне пропадает, так что нижняя ступень 0,44 стоит
 * дважды — у 4-го и 8-го человека. Их разводит рисунок (точка и шахматка), а сама
 * полоса в списке всегда подписана именем.
 *
 * Старое поле person.color (мятный, синий, кирпичный из первой версии) не читается:
 * оно из палитры, которой больше нет.
 */

import type { Person } from './types.ts'

/** Личная метка участника. */
export interface PersonTone {
  /** место в наборе меток, 0…7 */
  i: number
  /** насыщенность янтаря в метке: 1 — полный цвет, ниже — разбавленный подложкой */
  alpha: number
  /**
   * Насыщенность той же метки в полосе готовности. Разброс здесь шире, чем у alpha,
   * и это не небрежность: метка лежит на светлой подложке кружка, где бледный янтарь
   * теряет контраст (нужно 3 : 1), а полоса — на приглушённом `--zebra`, где можно
   * позволить куда более бледный тон. Одна общая насыщенность делала полосы разных
   * людей почти неразличимыми.
   */
  barAlpha: number
  /** рисунок внутри кружка — различает людей там, где цвет не читается */
  pattern: 'solid' | 'ring' | 'half' | 'dot' | 'quarter' | 'twin' | 'diag' | 'checker'
  /** словами: для подписи скринридеру и для подсказок */
  name: string
}

/**
 * Восемь меток: столько человек влезает в поездку, не повторившись. Первые четыре —
 * ровно те, что были до правки 04.08.2026: их менять нельзя, команда к ним привыкла.
 */
const TONES: Omit<PersonTone, 'i'>[] = [
  { alpha: 1, barAlpha: 1, pattern: 'solid', name: 'сплошной кружок' },
  { alpha: 0.9, barAlpha: 0.8, pattern: 'ring', name: 'кружок-кольцо' },
  { alpha: 0.8, barAlpha: 0.6, pattern: 'half', name: 'кружок-половинка' },
  { alpha: 0.7, barAlpha: 0.44, pattern: 'dot', name: 'кружок с точкой' },
  { alpha: 0.95, barAlpha: 0.92, pattern: 'quarter', name: 'кружок с четвертью' },
  { alpha: 0.85, barAlpha: 0.72, pattern: 'twin', name: 'кружок с двумя точками' },
  { alpha: 0.78, barAlpha: 0.56, pattern: 'diag', name: 'кружок по диагонали' },
  { alpha: 0.72, barAlpha: 0.44, pattern: 'checker', name: 'кружок-шахматка' },
]

/**
 * Метка человека. Считается от его места в S.people — не от me и не от порядка на экране,
 * иначе метка «переезжала» бы с человека на человека при смене читателя.
 */
export function toneOf(people: Person[], personId: string): PersonTone {
  const idx = people.findIndex((p) => p.id === personId)
  const k = idx < 0 ? 0 : idx % TONES.length
  return { i: k, ...TONES[k] }
}

/**
 * Список людей от лица читателя: он первый, остальные — в порядке документа.
 * Без `meId` (или если такого человека нет) возвращается исходный порядок.
 */
export function orderedPeople(people: Person[], meId?: string | null): Person[] {
  if (!meId) return people
  const idx = people.findIndex((p) => p.id === meId)
  if (idx <= 0) return people
  return [people[idx], ...people.slice(0, idx), ...people.slice(idx + 1)]
}
