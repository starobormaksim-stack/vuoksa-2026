import type { Rent, State } from './types'
import { fuelTotal, rentSum } from './calc'

/**
 * Проекция чужих коллекций в раздел «Расходы».
 *
 * ─── Зачем ───
 * Заказчик 09.08.2026, дословно: «я до сих пор не понимаю, почему ты не сделал
 * сворачивающиеся строки логистики и не соотнёс их с прочими затратами.
 * Логистика должна быть одним из подразделов внутри расходов, но ты этого
 * не сделал… я тебе говорил, вот, и не доделал до сих пор». И тем же
 * разговором — «ты проживание фиксируешь тоже как подраздел внутри расходов,
 * потому что это расходы в том числе», «а вот меню идёт отдельно».
 *
 * То есть «Расходы» — это раздел с подразделами: статьи закупки, «Аренда»,
 * «Логистика», «Проживание». Все одной формой, все сворачиваемые, у каждого
 * свои колонки.
 *
 * ─── Что здесь есть и чего здесь НЕТ ───
 * Здесь только ПОКАЗ: какие подразделы у «Расходов», из какой коллекции берётся
 * каждый и сколько в нём денег. Своих записей в документ этот слой не делает
 * ни одной, и своей арифметики не содержит: суммы приходят из `lib/calc.ts`,
 * иначе контрольные цифры (330 км · 21 385 / 26 005 / 47 390 / 11 848 ₽ ·
 * 2 канистры) разошлись бы между экраном и расчётом.
 *
 * ⛔ Коллекции НЕ сливаются. `S.buy`, `S.transport`, `S.fuelPrices`, `S.rent`,
 * `S.canRows` остаются каждая своей: метки удаления привязаны к имени коллекции
 * (`del['rent:' + i]`), а слияние полей — к спискам в `merge.ts`. Слить их
 * значило бы стереть `nt`, `blocks`, `calcT`, `warn`, `rateU`, `carry`, `kmSrc`,
 * `tone`, `color`, `owner`. Меняется ЭКРАН, а не форма хранения (постулат 4).
 */

/**
 * Категория аренды, которой платят за ночёвку.
 *
 * Заказчик 08.08.2026, диктуя, что такое аренда: «Аренда может быть и в сутках,
 * и в часах, и в минутах, это может быть место проживания, это может быть,
 * кстати, парковка». То есть ночёвка — это уже аренда, просто своей категории.
 * Категория `place` («Место и кемпинг») лежит в `S.rentCats` с первой версии
 * и есть в каждом документе — новой сущности заводить не пришлось.
 */
export const STAY_CAT = 'place'

/** Имя коллекции-источника: от него зависят метки удаления и слияние. */
export type SpendSrc = 'buy' | 'rent' | 'transport'

/** Один подраздел «Расходов», собранный проекцией. */
export interface SpendBlock {
  /** ключ свёртки (`foldpref.ts`) — уникален на весь лист */
  key: string
  /** откуда взяты строки */
  src: SpendSrc
  /** ключ своего названия в `S.secTitles` (`lib/sectitles.ts`) */
  secId: string
  /** заводское название — пока человек не переименовал подраздел */
  title: string
  /** итог подраздела; считает только `lib/calc.ts` */
  sum: number
  /** сколько строк лежит в источнике */
  count: number
}

const byOrd = (a: Rent, b: Rent) => a.ord - b.ord

/**
 * Строки аренды, которые НЕ про ночёвку, — подраздел «Аренда».
 * Парковка остаётся здесь: «парковка вписывается просто внутри неё».
 */
export function rentRows(S: State): Rent[] {
  return S.rent.filter((r) => r.cat !== STAY_CAT).sort(byOrd)
}

/** Строки аренды про ночёвку — подраздел «Проживание». */
export function stayRows(S: State): Rent[] {
  return S.rent.filter((r) => r.cat === STAY_CAT).sort(byOrd)
}

/** Итог подраздела «Аренда», ₽. */
export function rentOwnTotal(S: State): number {
  return rentRows(S).reduce((sum, r) => sum + rentSum(r), 0)
}

/** Итог подраздела «Проживание», ₽. */
export function stayTotal(S: State): number {
  return stayRows(S).reduce((sum, r) => sum + rentSum(r), 0)
}

/**
 * Подразделы «Расходов», которые собраны из чужих коллекций.
 *
 * Статей закупки здесь нет намеренно: они и так живут в `S.buySections`
 * со своими названиями, и второй список их порядка разошёлся бы с первым.
 */
export function spendBlocks(S: State): SpendBlock[] {
  return [
    {
      key: 'spend:rent',
      src: 'rent',
      secId: 'rent',
      title: 'Аренда',
      sum: rentOwnTotal(S),
      count: rentRows(S).length,
    },
    {
      /* Имя «Логистика» выбрано заказчиком окончательно 09.08.2026: «мы,
         во-первых, его назвали транспорт или логистика — давай так, это будет
         логистика». Своё название лежит в `S.secTitles.log` с первой версии. */
      key: 'spend:log',
      src: 'transport',
      secId: 'log',
      title: 'Логистика',
      sum: fuelTotal(S),
      count: S.transport.length,
    },
    {
      key: 'spend:stay',
      src: 'rent',
      secId: 'stay',
      title: 'Проживание',
      sum: stayTotal(S),
      count: stayRows(S).length,
    },
  ]
}
