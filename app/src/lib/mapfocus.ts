/**
 * Связь «Тайминга» с картой.
 *
 * Тайминг живёт в «Дороге», карта — в «Поездке», и на едином лендинге это два места
 * одной страницы. Тап по адресу точки должен прокрутить страницу к карте и показать
 * там именно эту точку, а если координат у точки ещё нет — предложить поставить её
 * тапом по карте. Прямой ссылки между разделами нет и быть не должно, поэтому просьба
 * передаётся через этот маленький посредник: кто угодно просит, карта слушает.
 */

import { scrollToSection } from '../sections.ts'

/** Что просят у карты. */
export type MapMode =
  /** показать точку: карта наводится на её координаты */
  | 'show'
  /** поставить точку: следующий тап по карте задаёт координаты именно ей */
  | 'place'

export interface MapRequest {
  pointId: string
  mode: MapMode
  /** метка времени: по ней карта отличает новую просьбу от той же самой */
  at: number
}

type Listener = (r: MapRequest) => void
const listeners = new Set<Listener>()

/** Подписаться на просьбы. Возвращает отписку. */
export function onMapRequest(l: Listener): () => void {
  listeners.add(l)
  return () => {
    listeners.delete(l)
  }
}

/**
 * Попросить карту показать точку (или дать поставить её).
 * Сначала прокручиваем страницу к «Поездке», потом зовём карту: иначе карта
 * наводится, пока её ещё не видно, и человек этого не замечает.
 */
export function askMap(pointId: string, mode: MapMode): void {
  scrollToSection('trip')
  const r: MapRequest = { pointId, mode, at: Date.now() }
  listeners.forEach((l) => l(r))
}
