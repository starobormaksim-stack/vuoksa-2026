/**
 * Просьбы к карте от тех, кто стоит рядом с ней.
 *
 * ⛔ Прежде здесь жила двусторонняя связь ленты точек и карты: лента просила
 * карту навестись, карта просила ленту подсветить строку (`focusInList`).
 * Ленты больше нет — заказчик 06.08.2026: «Да, она не нужна вообще. Просто
 * список точек на карте», — и обратный ход ушёл вместе с ней: точка целиком
 * правится в карточке своей метки (`map/MapPointCard.tsx`), подсвечивать
 * в другом месте нечего.
 *
 * Осталось три просьбы, и все идут К карте:
 *   «покажи точку маршрута» (askMapPoint)  — от поиска по листу;
 *   «покажи это место»      (askMapLook)   — от обложки поездки;
 *   «дай поставить конечную» (askPlaceMain) — оттуда же.
 */

import { scrollToSection } from '../sections.ts'

/* ─────────── просьба «покажи точку маршрута» ─────────── */

type PointListener = (r: { pointId: string; at: number }) => void
const pointWatchers = new Set<PointListener>()

/** Подписаться на «открой карточку этой точки». Возвращает отписку. */
export function onMapPoint(l: PointListener): () => void {
  pointWatchers.add(l)
  return () => {
    pointWatchers.delete(l)
  }
}

/**
 * Показать точку маршрута на карте и открыть её карточку.
 *
 * Единственный оставшийся проситель — поиск по листу: точка находится по
 * названию и по описанию, а показать её теперь можно только на карте.
 * Прыжок к строке (`jumpToItem`) для точек больше не работает вовсе — строки
 * нет, и молчаливый отказ здесь был бы прямым нарушением постулата 5.
 */
export function askMapPoint(pointId: string): void {
  scrollToSection('trip')
  const at = Date.now()
  pointWatchers.forEach((l) => l({ pointId, at }))
}

/* ─────────── просьба «покажи это место» ─────────── */

/** Куда навести карту: голые координаты, без точки маршрута. */
export interface LookRequest {
  lat: number
  lon: number
  /** метка времени: по одному и тому же месту можно попросить дважды подряд */
  at: number
}

type LookListener = (r: LookRequest) => void
const lookWatchers = new Set<LookListener>()

/** Подписаться на «наведись сюда». Возвращает отписку. */
export function onMapLook(l: LookListener): () => void {
  lookWatchers.add(l)
  return () => {
    lookWatchers.delete(l)
  }
}

/**
 * Показать место на карте.
 *
 * Заведено под слова заказчика 05.08.2026 про место поездки на обложке: «здесь
 * при нажатии нужно не только название выбрать, но и можно точку показать.
 * Участники могут просмотреть, что это такое. Менять они не смогут». Просьба
 * идёт от координат, а не от точки маршрута: главное место поездки живёт
 * в `trip.places`, точкой маршрута оно не является.
 */
export function askMapLook(lat: number, lon: number): void {
  const r: LookRequest = { lat, lon, at: Date.now() }
  lookWatchers.forEach((l) => l(r))
}

/* ─────────── просьба «дай поставить место поездки» ─────────── */

type PlaceListener = (at: number) => void
const placeWatchers = new Set<PlaceListener>()

/** Подписаться на «жди тапа для конечной точки». Возвращает отписку. */
export function onAskPlaceMain(l: PlaceListener): () => void {
  placeWatchers.add(l)
  return () => {
    placeWatchers.delete(l)
  }
}

/**
 * Место поездки ещё не стоит на карте — включить режим постановки.
 *
 * Заказчик 06.08.2026 про иконку у названия места: «если там пусто — он тебе
 * предлагает указать точку, указываешь точку и прописываешь название». Раньше
 * у места без координат органа не было вовсе (постулат 6 читался как «показывать
 * нечего»), и человек упирался в тупик: кнопка «Конечная» стоит под картой,
 * а связи между ней и строкой места не было. Теперь один и тот же орган
 * либо показывает место, либо даёт его поставить.
 */
export function askPlaceMain(): void {
  scrollToSection('trip')
  const at = Date.now()
  placeWatchers.forEach((l) => l(at))
}
