/**
 * Общий «плюс»: четыре вида новой позиции, доступные из любого раздела.
 *
 * ─── Слово заказчика (06.08.2026, дословно) ───
 * «Захотел добавить что-то новое — у меня есть всегда при прокрутке… с правой
 * стороны плюсик, оно как бы прилипает… будет возможность добавить: расчёт
 * с топливом, расчёт с арендой (аренда, причём сутки, день, минуты), товар
 * какой-то другой купить, либо просто вещь добавить, которая не стоит ничего,
 * но она вот есть.»
 *
 * ─── Как это уживается с постулатом 3.5 ───
 * «Один список — один раздел» никуда не девается: общий плюс НЕ показывает
 * чужие списки и ничего не дублирует. Он только ЗАВОДИТ строку — и всегда в том
 * разделе, где этот вид живёт, после чего уводит туда человека (`jumpToItem`).
 * Вещь ложится в «Сборы», покупка в «Закупку», топливо и аренда — в «Дорогу».
 *
 * ─── Почему заявка, а не общая функция создания ───
 * Как заводится строка, знает сам раздел: у «Сборов» это перенумерация блока,
 * у «Закупки» — своя `ord`, у «Дороги» — вид техники и цена топлива из
 * справочников. Переносить это в общее место значило бы завести вторую копию
 * правил создания, которая разойдётся с первой. Поэтому общий плюс лишь
 * ПРОСИТ раздел добавить своё, а раздел выполняет просьбу собственными руками —
 * теми же, что и по своей кнопке.
 *
 * ─── Почему не шторка ───
 * Попапы забракованы трижды (постулат 2). Виды выбираются рядом кнопок на месте,
 * по образцу `UnitPick` в `gear/GearMatrix.tsx`.
 */
import { useSyncExternalStore } from 'react'
import type { Perms } from './perm'
import { goSection, sectionInView } from './jump'

export type AddKind = 'gear' | 'buy' | 'fuel' | 'rent'

export interface AddKindDef {
  kind: AddKind
  /** подпись на кнопке: ряд из четырёх обязан помещаться на 390 */
  label: string
  /** раздел, в котором эта позиция живёт (постулат 3.5) */
  section: string
  /** что читается вслух: короткой подписи для этого мало */
  aria: string
  /** расчёты правит только редактор; вещь и покупку заводит любой участник */
  editorOnly: boolean
}

/**
 * Порядок назван заказчиком: сначала то, что добавляют часто.
 * ⚠️ «Топливо» — это строка расчёта, то есть техника с расходом: он назвал её
 * «расчёт с топливом». Полное название читается вслух и в подсказке.
 */
export const ADD_KINDS: AddKindDef[] = [
  {
    kind: 'gear',
    label: 'Вещь',
    section: 'gear',
    aria: 'Добавить вещь в «Сборы»',
    editorOnly: false,
  },
  {
    kind: 'buy',
    label: 'Покупка',
    section: 'buy',
    aria: 'Добавить покупку в «Закупку»',
    editorOnly: false,
  },
  {
    kind: 'fuel',
    label: 'Топливо',
    section: 'road',
    aria: 'Добавить расчёт с топливом — технику в «Дороге»',
    editorOnly: true,
  },
  {
    kind: 'rent',
    label: 'Аренда',
    section: 'road',
    aria: 'Добавить аренду в «Дороге» — сутки, часы или минуты',
    editorOnly: true,
  },
]

/**
 * Что человеку положено заводить. Постулат 6: не положено — кнопки нет,
 * серых кнопок и отказов не бывает.
 */
export function allowedKinds(perms: Perms): AddKindDef[] {
  const editor = perms.isEditor()
  const inTrip = editor || !!perms.me
  return ADD_KINDS.filter((k) => (k.editorOnly ? editor : inTrip))
}

/* ─────────── заявка разделу ─────────── */

let seq = 0
const asked: Record<AddKind, number> = { gear: 0, buy: 0, fuel: 0, rent: 0 }
/** был ли человек в этом разделе в момент нажатия — см. `askedHere` */
const here: Record<AddKind, boolean> = { gear: false, buy: false, fuel: false, rent: false }
const subs = new Set<() => void>()

function subscribe(f: () => void): () => void {
  subs.add(f)
  return () => {
    subs.delete(f)
  }
}

/**
 * Попросить раздел завести позицию и увести туда человека.
 *
 * ⚠️ «Здесь ли он» меряется ДО прокрутки: после неё раздел назначения уже
 * на экране всегда, и признак стал бы бесполезным.
 */
export function requestAdd(kind: AddKind): void {
  const def = ADD_KINDS.find((k) => k.kind === kind)
  if (!def) return
  here[kind] = sectionInView(def.section)
  asked[kind] = ++seq
  subs.forEach((f) => f())
  goSection(def.section)
}

/**
 * Читал ли человек этот раздел, когда нажимал.
 *
 * Да — позиция ложится в блок, который у него перед глазами (так работает
 * кнопка раздела сегодня). Нет — в первый блок: `visibleBlockId` в этот момент
 * мерил бы ещё не доехавшую прокрутку и клал бы строку наугад.
 */
export function askedHere(kind: AddKind): boolean {
  return here[kind]
}

/** Номер последней заявки этого вида: изменился — раздел заводит строку. */
export function useAddRequest(kind: AddKind): number {
  return useSyncExternalStore(
    subscribe,
    () => asked[kind],
    () => 0,
  )
}
