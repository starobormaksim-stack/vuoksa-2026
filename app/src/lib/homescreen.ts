/**
 * Значок на домашнем экране открывает СВОЙ лист, без сети и без повторного входа.
 *
 * ─── Чего хочет заказчик (06.08.2026, после трёх неудачных заходов) ───
 * «Сохранение входа должно работать как у владельца, так и у участников… везде
 * всё должно работать, и иконка должна адекватно отображаться как на айфонах,
 * так и на андроидах». И отдельно: «было бы круто, чтобы вот эта добавленная
 * домой ссылка являлась офлайн-версией».
 *
 * ─── Почему две системы решаются по-разному ───
 * С iOS 14 значок-приложение делит с Safari служебного работника и его кеш,
 * но НЕ делит `localStorage` и куки. Вход лежит именно в `localStorage`
 * (`flops.auth`), поэтому в режиме приложения он и пропадал — три раза подряд.
 *
 * Отсюда развилка, и она НЕ «офлайн или вход», как думалось раньше:
 *
 *   iPhone  — значок остаётся ЗАКЛАДКОЙ Safari. Хранилище то же, значит вход
 *             на месте сам собой; работник и его кеш те же, значит офлайн тоже
 *             на месте и уже прогрет. Для этого манифеста быть не должно вовсе:
 *             манифест с `display: standalone` и есть то, что превращает значок
 *             в отдельное приложение. Тега нет в разметке, и здесь мы его на iOS
 *             не вешаем (У-107).
 *   Android — значок ставит Chrome, хранилище у него общее с браузером, и полное
 *             приложение только на пользу. Манифест вешаем, сразу личный:
 *             `start_url` — ссылка этого человека (У-103).
 *
 * ⛔ Личная ссылка НЕ уезжает в файл сайта: манифест собирается в браузере
 * и живёт как `blob:` только в этой вкладке (У-65 — ключи в публичной сборке
 * недопустимы). Статический `manifest.webmanifest` остаётся общим и без ключей.
 *
 * ─── Страховка на случай, если система всё же заведёт приложение ───
 * `помнитьМеня()` кладёт личную ссылку в кеш служебного работника, а он у Safari
 * и у значка ОБЩИЙ. Приложение, у которого своё пустое `localStorage`, достаёт
 * оттуда ссылку и уводит себя на неё (`вспомнитьСебя()` зовётся из `main.tsx`).
 * Стоит это ничего, а закрывает ровно ту дыру, на которой сгорели три захода.
 */

import { linkFor } from './perm.ts'
import type { Person } from './types.ts'

/** Что кладём в личный манифест сверх общего. Остальное берём из файла. */
interface Personal {
  start_url: string
  id: string
}

let текущий = ''
let прежнийBlob = ''

/** Общий манифест сайта — без ключей, из него собирается личный (только Android). */
const ОБЩИЙ_МАНИФЕСТ = import.meta.env.BASE_URL + 'manifest.webmanifest'

/**
 * Кеш, в котором лежит личная ссылка.
 *
 * ⛔ Имя обязано начинаться на `pine-me`: `sw.js` в `activate` сносит все кеши,
 * кроме своего текущего, и без этой оговорки страховка стиралась бы при каждой
 * выкладке. Оговорка стоит там же, в `activate`.
 */
const КЕШ_ЛИЧНОСТИ = 'pine-me'
/** Адрес-выдумка: настоящего файла по нему нет, кеш просто хранит по ключу. */
const АДРЕС_ЛИЧНОСТИ = 'pine-me/link'

/**
 * Запомнить личную ссылку там, где её увидит и значок-приложение.
 *
 * Кеш служебного работника с iOS 14 общий у Safari и у значка, а `localStorage`
 * у них разный. Значит это единственное место, через которое вход переезжает
 * в приложение, если система всё-таки его заведёт.
 */
async function помнитьМеня(me: Person): Promise<void> {
  if (typeof caches === 'undefined') return
  const link = myLink(me)
  if (!link) return
  try {
    const c = await caches.open(КЕШ_ЛИЧНОСТИ)
    await c.put(АДРЕС_ЛИЧНОСТИ, new Response(link, { headers: { 'content-type': 'text/plain' } }))
  } catch {
    /* хранилище закрыто (приватный режим) — работаем без страховки */
  }
}

/**
 * Достать личную ссылку из общего кеша.
 *
 * Зовётся из `main.tsx` ровно тогда, когда идти больше не с чем: ни ключа
 * в адресе, ни запомненного входа, ни кода из письма. В этот момент человек
 * всё равно увидел бы «Этот лист закрыт», так что ожидание ничего не стоит.
 *
 * Возвращает адрес, на который надо увести, либо пустую строку.
 */
export async function вспомнитьСебя(): Promise<string> {
  if (typeof caches === 'undefined' || typeof location === 'undefined') return ''
  try {
    const c = await caches.open(КЕШ_ЛИЧНОСТИ)
    const hit = await c.match(АДРЕС_ЛИЧНОСТИ)
    if (!hit) return ''
    const link = (await hit.text()).trim()
    /* Своя же ссылка на своём же домене — чужой адрес отсюда взяться не может,
       но проверить дешевле, чем однажды увести человека наружу. */
    if (!link || new URL(link, location.href).origin !== location.origin) return ''
    if (!/[?&]k=/.test(link)) return ''
    return link
  } catch {
    return ''
  }
}

/** Личная ссылка этого человека на этом сайте — с ключом и поездкой. */
function myLink(me: Person): string {
  return linkFor(me)
}

/**
 * Это iPhone или iPad.
 *
 * Считаем по строке браузера и по «мак с касанием» — так iPad с iPadOS 13+
 * представляется настольным Safari. Ошибиться в эту сторону не страшно:
 * худшее, что случится, — значок останется закладкой браузера, то есть будет
 * работать ровно так, как работал сайт.
 */
function isIOS(): boolean {
  if (typeof navigator === 'undefined') return false
  const ua = navigator.userAgent || ''
  if (/iPhone|iPad|iPod/i.test(ua)) return true
  return /Macintosh/i.test(ua) && (navigator.maxTouchPoints || 0) > 1
}

/**
 * Держать в адресной строке личную ссылку.
 *
 * ⛔ Без этого ярлык на iPhone бесполезен. Safari добавляет на домашний экран
 * ТОТ АДРЕС, который сейчас в строке (личный манифест он может и не принять —
 * это `blob:`), а у владельца, вошедшего по письму, в адресе ни имени, ни ключа:
 * код из письма стирается сразу после обмена. Ярлык запоминался «голым», в новом
 * хранилище приложения не было ни ключа, ни сеанса почты — и человек снова
 * упирался во вход. Заказчик 06.08.2026: «я только что зарегистрировался
 * в Safari, сделал иконку домой, захожу — и у меня опять просят вписать. Я уже
 * должен быть зарегистрирован» (У-105).
 *
 * Страницу не перезагружаем: `replaceState` меняет только строку адреса.
 * Историю не засоряем — заменяем текущую запись, а не добавляем новую.
 *
 * ⚠️ Список поездок (`?trips=1`) не трогаем: его метку снимает `closeTripsList()`,
 * и подмена адреса из-под неё вернула бы человека в список после обновления.
 */
function keepPersonalUrl(me: Person): void {
  if (typeof location === 'undefined' || typeof history === 'undefined') return
  if (!me.key) return
  const q = new URLSearchParams(location.search)
  if (q.has('trips')) return
  if (q.get('k') === me.key && q.has('u')) return
  /* Прочие метки адреса остаются как были — в том числе `trip` и `sandbox`:
     потерять `sandbox=1` значит увести проверку в боевую строку (У-01). */
  q.set('u', me.slug || me.id)
  q.set('k', me.key)
  const s = q.toString()
  history.replaceState(null, '', location.pathname + (s ? '?' + s : '') + location.hash)
}

/**
 * Подменить манифест на личный.
 *
 * Зовётся, когда человек опознан. Повторный вызов с той же ссылкой ничего
 * не делает: перевешивать `<link>` на каждый рендер незачем.
 */
export async function personalizeManifest(me: Person | null): Promise<void> {
  if (typeof document === 'undefined' || typeof URL === 'undefined') return
  if (!me) return
  /* Первым делом — адрес: на него смотрит Safari, когда кладёт значок на экран. */
  keepPersonalUrl(me)
  /* И сразу же — в общий кеш, пока человек точно опознан. */
  void помнитьМеня(me)

  const start = myLink(me)
  if (!start || start === текущий) return

  /* ⛔ На iPhone манифеста нет и не будет. Его присутствие — единственное, что
     превращает значок в отдельное приложение с пустым хранилищем (У-107).
     В разметке тега нет; здесь мы его на iOS просто не заводим. */
  if (isIOS()) return

  /* Общий манифест читаем с сайта — так личный отличается от него ровно
     одним полем и не расходится с ним при правках. */
  let base: Record<string, unknown>
  try {
    const res = await fetch(ОБЩИЙ_МАНИФЕСТ, { cache: 'no-store' })
    if (!res.ok) return
    base = (await res.json()) as Record<string, unknown>
  } catch {
    /* манифеста нет или он не читается — значок останется обычной закладкой */
    return
  }

  /* Тега в разметке нет (см. шапку файла) — заводим свой. */
  let link = document.querySelector<HTMLLinkElement>('link[rel="manifest"]')
  if (!link) {
    link = document.createElement('link')
    link.rel = 'manifest'
    document.head.appendChild(link)
  }

  const personal: Personal = {
    start_url: start,
    /* `id` держит ярлык привязанным к одному приложению, даже если ссылка
       поменяется (смена ключа в «Команде»): иначе телефон завёл бы второй
       значок рядом со старым. */
    id: new URL('./', location.href).href,
  }
  const doc = { ...base, ...personal, scope: new URL('./', location.href).href }

  try {
    const blob = new Blob([JSON.stringify(doc)], { type: 'application/manifest+json' })
    const url = URL.createObjectURL(blob)
    link.setAttribute('href', url)
    if (прежнийBlob) URL.revokeObjectURL(прежнийBlob)
    прежнийBlob = url
    текущий = start
  } catch {
    /* браузер не дал собрать файл — работаем с общим манифестом */
  }
}
