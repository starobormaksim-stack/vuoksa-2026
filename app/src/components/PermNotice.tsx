import { useTrip } from '@/store'
import { permName } from '@/lib/perm'

/**
 * Полоска «почему у меня такие права».
 *
 * Заказчик 04.08.2026: «у Кости ничего редактировать невозможно» и «какого хрена ты
 * меня ссылаешь за Костей, когда я являюсь владельцем». Оба раза права были исправны —
 * молчал интерфейс. Постулат 4: молчаливых отказов не бывает.
 *
 * Показываем ровно то, что человек не может увидеть сам, и в порядке важности:
 *
 *   1. что только что произошло (вышли из сеанса) — сообщение живёт секунд пятнадцать;
 *   2. чем кончилась сверка входа по почте с листом (store.ts, SignIn);
 *   3. ключ не подошёл вовсе — права менялись, ссылка погасла (`perms.stale`);
 *   4. в документе человек редактор или владелец, а на руках права участника.
 *
 * У вошедшего владельца и у настоящего участника полоски нет: у них всё сошлось.
 */
export function PermNotice() {
  const { perms, signIn } = useTrip()
  const me = perms.mePerson
  const должен = me?.perm ?? 'member'
  const урезаны = !!me && должен !== 'member' && perms.perm === 'member'

  const текст = сообщение()

  if (!текст) return null

  return (
    <div
      role="status"
      aria-live="polite"
      className="pointer-events-none fixed inset-x-0 bottom-[calc(env(safe-area-inset-bottom)+4.5rem)] z-40 flex justify-center px-4 lg:inset-x-auto lg:right-6 lg:bottom-6 lg:justify-end"
    >
      <p className="pointer-events-auto max-w-[32rem] rounded-xl border border-line bg-surface px-4 py-3 text-note text-muted shadow-lg">
        {текст}
      </p>
    </div>
  )

  function сообщение(): string {
    if (signIn.note) return signIn.note

    /* Вход по почте. «owner» и «none» ничего не объясняют — там всё сошлось. */
    if (signIn.state === 'unclaimed')
      return `Лист ещё не закреплён ни за какой почтой. Первая же ваша правка закрепит его за ${signIn.email} — после этого входить по почте сможете только вы.`
    if (signIn.state === 'foreign')
      return `Вы вошли как ${signIn.email}, но лист закреплён за другой почтой — полные права она не даёт. Права владельца даёт та почта, с которой лист заводили; всё остальное — личная ссылка от владельца.`
    if (signIn.state === 'nochief')
      return `Вы вошли как ${signIn.email}, но в списке команды нет ни одного владельца — передать полные права некому. Назначьте владельца в разделе «Команда» или откройте свою личную ссылку.`
    if (signIn.state === 'unknown')
      return signIn.reason === 'нет-колонки'
        ? `Вы вошли как ${signIn.email}, но лист пока не умеет узнавать владельца по почте — в базе не хватает одной настройки. Права сейчас даёт личная ссылка.`
        : signIn.reason === 'нет-ключа'
          ? `Вы вошли как ${signIn.email}, но лист закрыт от посторонних и ключа этого браузера не признал — по одной почте он владельца не отдаёт. Откройте свою личную ссылку целиком, вместе с ключом.`
          : `Вы вошли как ${signIn.email}, но проверить владельца листа не вышло — нет связи с сервером. Пока права даёт личная ссылка; обновите страницу, когда связь вернётся.`

    if (perms.stale)
      return `Ссылка устарела: права ${me?.name ?? 'этого человека'} менялись, и старая ссылка погасла. Попросите новую у владельца.`
    if (урезаны)
      return `Открыта страница ${me?.name ?? 'участника'}, но ключ не подтверждён — сейчас права как у участника, хотя в списке команды ${permName(должен).toLowerCase()}. Откройте личную ссылку целиком, вместе с ключом.`
    return ''
  }
}
