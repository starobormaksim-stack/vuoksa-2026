import { useState } from 'react'
import type { State } from '@/lib/types'
import type { Perms } from '@/lib/perm'
import { update } from '@/store'
import { autoDayTitle, fmtRange, isAutoDayTitle, withDate } from '@/format'
import { touch } from '@/store'
import { TripMap } from '@/components/map/TripMap'
import { TripCover } from './TripCover'
import { DateRangePicker } from './DateRangePicker'

/**
 * Раздел «Поездка»: обложка и карта — двумя одинаковыми блоками.
 *
 * Блок «Кто уже собрался» удалён заказчиком 04.08.2026 («убери вообще этот блок,
 * он не нужен») — сразу за обложкой на странице идёт раздел «Команда».
 * Разбор «Как это считается» с обложки тоже убран: расчёты живут в «Дороге».
 *
 * ⛔ 05.08.2026 отсюда убран и `ReadyLeft` — колонка несобранного справа от обложки.
 * Дословно: «у тебя дублируется список товаров на всём протяжении… больше нигде
 * не повторяться списками оборудования, инвентаря, вещей или продуктов» (урок У-53).
 * Он перечислял позиции `S.gear` чужого раздела, да ещё и печатал названия его
 * групп. Сводка о сборах осталась там, где ей и место, — числом «собрано X из Y»
 * в шапке самих «Сборов». Обложка теперь занимает всю ширину контейнера на всех
 * ширинах: делить её было не с кем.
 *
 * Даты меняют только владелец и редактор.
 */
export function TripSection({ S, perms }: { S: State; perms: Perms }) {
  const [calOpen, setCalOpen] = useState(false)
  const canEdit = perms.isEditor()

  const saveDates = (a: Date, b: Date) => {
    const start = withDate(S.trip.start, a, '07:30:00')
    update((s) => ({
      ...s,
      trip: {
        ...s.trip,
        start,
        end: withDate(s.trip.end, b, '18:00:00'),
        dates: fmtRange(a, b),
        datesAuto: true,
      },
    }))
    /* Пункт 6 разбора: даты заводятся ОДИН раз, здесь, и дальше появляются сами.
       Раскладка — единственное место, где их приходилось вписывать второй раз
       руками («10 августа · день 1»). Переписываем только те названия дней,
       которые выданы автоматом или пусты: «День рыбалки» человек назвал сам,
       и трогать его нельзя (постулат 4 — ничего из данных не выбрасывать). */
    update((s) => {
      for (const [idx, d] of (s.menu ?? []).entries()) {
        if (d.t.trim() && !isAutoDayTitle(d.t)) continue
        const next = autoDayTitle(start, idx)
        if (!next || next === d.t) continue
        d.t = next
        touch(d)
      }
    })
    setCalOpen(false)
  }

  return (
    <div className="flex flex-col gap-4 lg:gap-6">
      {/* ⛔ Полосы раздела здесь больше НЕТ. Заказчик 06.08.2026: «здесь, где у тебя
          написано слово „Поездка“, не нужно вообще его — подними выше просто вот
          этот блок с обложкой и картой. И вот эту полоску удали. Элементы, которые
          лишними являются в сервисе, которые просто перегружают информацией людей, —
          и премиальность из-за этого теряется».
          Слово «Поездка» ничего не добавляло: название поездки написано на самой
          обложке первой строкой и правится там же. Своего имени в `S.secTitles`
          у этого раздела нет (ключи первой версии — buy, log, crew, gear, menu),
          поэтому и терять из документа нечего (У-04). У остальных разделов полоса
          остаётся: там она отделяет раздел от раздела при прокрутке. */}

      {/* ⛔ Здесь стояла строка принадлежности — «ВУОКСА · 2026 · ЮБИЛЕЙ ·
          10 лет · Вы — Макс, владелец». Заведена она была 06.08.2026 по его же
          просьбе («нормальное указание поездки… и человека, который зашёл»),
          а 07.08.2026 он попросил её убрать вместе с «2026, юбилей, 10 лет»
          и адресом места: «позорнейшее количество информации».

          И он прав по существу: название поездки стояло на экране ДВАЖДЫ —
          здесь и первой строкой самой обложки, крупным кеглем, где оно ещё
          и правится. Строка повторяла соседа, а не добавляла к нему.

          Кто вошёл — видно в верхней полосе: там стоит эмблема человека
          (`PresenceStack`), и это единственное место, где такое сообщение
          не спорит с названием поездки.
          ⛔ Обратно в полосу верхнего меню строку «Вы — …» класть нельзя:
          там она однажды срезала названия всех разделов (У-11). */}

      {/* ── Обложка и карта. Карте отдано больше места ──
          Заказчик 07.08.2026: «когда по ширине раскрываю, я хочу видеть её
          шире, а она у меня узкая по всему браузеру, очень узкая». Стояло
          `lg:grid-cols-2` — ровно пополам, и карта получала половину экрана.
          Теперь обложке отдана колонка фиксированной ширины, а карта берёт
          весь остаток: на 1280 это 416 px против 816 вместо 616 на 616.
          ⚠️ `minmax(0, …)` обязателен: без нуля в минимуме колонка обложки
          растягивается по самому длинному неразрывному куску названия —
          та же беда, от которой в самой обложке стоит `min-w-0`.
          Симметрию блоков это не ломает: высоту им по-прежнему равняет
          строка сетки (`items-stretch`), а форма рамки у них одна.

          ⚠️ Прежняя просьба 05.08.2026 — «слева блок обложки… а с правой
          стороны такой же блок с изображением карты… они абсолютно идентичны
          и симметрично выглядят друг с другом» — этим не отменена: блоки
          по-прежнему одной формы и одной высоты. Отменено только равенство
          ШИРИН, и отменил его он сам.

          Карта не продублирована, а ПЕРЕЕХАЛА сюда из «Дороги» (его решение,
          спрошено прямо): дублировать её значило бы завести второе место правки
          одних и тех же точек и вторую живую карту Google на странице.
          В «Дороге» остались лента точек со временем и расчёт дороги. */}
      <div className="grid min-w-0 grid-cols-1 gap-4 lg:grid-cols-[minmax(0,26rem)_1fr] lg:gap-6">
        <TripCover S={S} perms={perms} onEditDates={() => setCalOpen(true)} />
        {/* ⛔ Числовой высоты у блока на телефоне БОЛЬШЕ НЕТ (У-114). Стояло
            `h-[460px]`, а содержимого при боевых данных набиралось 572 px: строка
            поиска 61 + карта 280 (её `min-h-[280px]` сжаться не даёт) + нижняя
            полоса 230. Лишние 112 px срезал `overflow-hidden`, и за краем
            оказывались кнопки «Точка · Я здесь · Конечная» и строка «какая карта
            нарисована и какая сборка» — та, о которой заказчик просил отдельно
            (У-30…У-32). Невидимая строка равна отсутствующей.
            Высоту теперь задаёт содержимое: карта берёт свои 280 px минимума,
            полоса — сколько ей нужно, блок растёт под них. На десктопе как было:
            высоту даёт строка сетки, то есть соседний блок обложки. */}
        <TripMap
          S={S}
          perms={perms}
          className="border border-line shadow-md ring-0"
        />
      </div>

      {calOpen && canEdit && (
        <DateRangePicker
          start={new Date(S.trip.start)}
          end={new Date(S.trip.end)}
          onCancel={() => setCalOpen(false)}
          onDone={saveDates}
        />
      )}
    </div>
  )
}
