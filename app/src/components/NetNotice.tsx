import { useTrip } from '@/store'
import { isOfflineCopy } from '@/lib/offline'

/**
 * Полоска «правки не уходят на сервер».
 *
 * Появилась 04.08.2026 вместе с защитой листа (docs/rls-apply-b.sql). До неё
 * состояние связи считалось в store.ts, но НИ ОДИН компонент его не показывал:
 * пока писать разрешалось всем, это было незаметно. С включённой защитой стало
 * опасно — человек, открывший сайт без своей ссылки, отмечал бы вещи в пустоту
 * и ничего бы не заподозрил. Молчаливая потеря правок хуже честного отказа.
 *
 * Показываем только настоящие беды («err») и работу без сети («off»). Состояния
 * «ok» и «work» не показываем вовсе: мигающая полоска при каждом сохранении
 * раздражала бы и обесценила бы саму полоску.
 *
 * Место — над нижней панелью разделов на мобильном и в правом нижнем углу
 * на десктопе. Полоска ничего не перекрывает и не требует нажатия.
 */
export function NetNotice() {
  const { net } = useTrip()
  /* Офлайн-копия на сервер и не ходит: сеть в ней закрыта наглухо (lib/offline.ts),
     и про это уже сказано полоской наверху самого файла. Красное «нет связи»
     здесь было бы неправдой — это не беда, а устройство копии. */
  if (isOfflineCopy()) return null
  if (net.state !== 'err' && net.state !== 'off') return null

  /* Без сети — не беда, а обычное дело в лесу: правки лежат в браузере и уедут
     сами, когда связь вернётся. Отказ сервера — другое дело, о нём говорим резче. */
  const беда = net.state === 'err'
  const текст =
    net.msg ||
    (беда ? 'Правки не уходят на сервер' : 'Нет сети — правки пока остаются в браузере')

  return (
    <div
      role="status"
      aria-live="polite"
      className="pointer-events-none fixed inset-x-0 bottom-[calc(env(safe-area-inset-bottom)+4.5rem)] z-40 flex justify-center px-4 lg:inset-x-auto lg:right-6 lg:bottom-6 lg:justify-end"
    >
      <p
        /* ⛔ `pointer-events-auto` здесь БЫЛО и накрывало кнопки под собой:
           плашка висит `fixed` над нижней панелью, нажатия в неё упирались,
           а нажать в ней нечего — это `role="status"`, а не орган. Полоска
           теперь насквозь прозрачна для пальца, как и её обёртка. */
        className={`max-w-[32rem] rounded-xl border bg-surface px-4 py-3 text-note shadow-lg ${
          беда ? 'border-danger/40 text-danger' : 'border-line text-muted'
        }`}
      >
        {текст}
      </p>
    </div>
  )
}
