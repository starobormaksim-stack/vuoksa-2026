import type { Buy, State } from '@/lib/types'
import { counted, planSumOf, statusName, sumOf } from '@/lib/buyx'

/**
 * Мелочи раздела «Закупка», которых нет в общей библиотеке.
 *
 * Здесь же живёт главный переход переделки 04.08.2026: поле «Статус» ушло с экрана
 * («не надо статуса, вообще нахер он не нужен»), но НЕ ушло из данных. `Buy.st`
 * по-прежнему решает, идёт ли позиция в общую сумму (`lib/calc.ts` не тронут),
 * а на экране от него остались две вещи:
 *
 *   • галочка «Берём» — включена, когда `st === 'buy'`;
 *   • слова «Есть у Кости» и «Под вопросом» — в описании под названием.
 *
 * Слова показываются РАСЧЁТОМ, документ при показе не переписывается: пока человек
 * строку не трогал, в ней лежит ровно то, что приехало с сервера. Как только он
 * правит описание или снимает-ставит галочку, foldStatus() перекладывает эти слова
 * в само описание и переводит `st` в 'skip' — арифметика при этом не меняется
 * ('has_*', 'ask' и 'skip' одинаково не входят в сумму), а текст не теряется.
 */

/**
 * Позиция закупки с отметками «кто сколько покупает».
 *
 * `o` — то же поле, что у сборов: id человека → сколько берёт на себя. Пусто —
 * покупают все вместе (правило заказчика «по умолчанию все»). Прежнее одиночное
 * `who` остаётся и пишется дальше: по нему считается «моё» в правах и живут
 * документы первой версии.
 */
export type BuyItem = Buy & { o?: Record<string, number> }

/** Порядок позиций внутри раздела. */
export function byOrd(a: Buy, b: Buy): number {
  return (a.ord ?? 0) - (b.ord ?? 0)
}

/** Сколько знаков после запятой показывать: 2 шт. — без дробной части, 0,5 кг — с ней. */
export function digitsOf(v: number): number {
  return Number.isInteger(v) ? 0 : 1
}

/** Слова прежнего статуса: «Есть у Кости», «Под вопросом». Для 'buy' и 'skip' — пусто. */
export function stWords(p: Buy, S: State): string {
  if (p.st === 'buy' || p.st === 'skip') return ''
  return statusName(p.st, S.people)
}

/** Описание строки: слова статуса впереди, дальше собственное примечание. */
export function descText(p: Buy, S: State): string {
  const w = stWords(p, S)
  if (!w) return p.c || ''
  return p.c ? `${w}. ${p.c}` : `${w}.`
}

/**
 * Переложить слова статуса в описание. Вызывается перед любой правкой статуса
 * или описания — чтобы «Есть у Кости» осталось написанным, а не исчезло вместе
 * с полем, которого больше нет на экране.
 */
export function foldStatus(p: Buy, S: State): void {
  const w = stWords(p, S)
  if (!w) return
  p.c = p.c ? `${w}. ${p.c}` : `${w}.`
  p.st = 'skip'
}

/** Сколько берёт на себя конкретный человек. Старое одиночное `who` читается как единица. */
export function buyerQty(p: BuyItem, id: string): number {
  const v = p.o?.[id]
  if (typeof v === 'number') return v
  return p.who === id ? 1 : 0
}

/**
 * Сколько взять на себя, когда человек только ставит галочку.
 *
 * Слово заказчика 06.08.2026: «купил 8 рулонов — галочку поставил». Единица
 * в этом месте врала: позиция на восемь штук с одним покупателем уходила
 * в перерасчёт как 1 из 8. Поэтому галочка кладёт ОСТАТОК — количество позиции
 * минус то, что уже разобрали остальные. Число рядом остаётся правимым:
 * взял меньше — поправил.
 *
 * ⛔ Меньше единицы не бывает: галочка означает «беру», а не «беру ноль».
 * Ни `lib/settle.ts`, ни `lib/calc.ts` при этом не тронуты — меняется только
 * то, какое число подставляется при первом нажатии.
 */
export function restQty(p: BuyItem, id: string): number {
  const bag = p.o ?? (p.who ? { [p.who]: 1 } : {})
  let taken = 0
  for (const [who, v] of Object.entries(bag)) if (who !== id) taken += v || 0
  /* Копейки от дробных количеств (0,5 кг) округляем: 8 − 0,1 − 0,2 не должно
     давать 7,699999999999999. */
  const rest = Math.round(((p.q || 0) - taken) * 100) / 100
  return rest > 1 ? rest : 1
}

/** Отметить человека покупателем (или снять отметку, если 0). */
export function setBuyer(p: BuyItem, id: string, qty: number, me: string): void {
  const o: Record<string, number> = { ...(p.o || {}) }
  /* Прежнее одиночное «покупает» переносим в отметки, иначе оно потерялось бы. */
  if (p.who && o[p.who] === undefined) o[p.who] = 1
  if (qty > 0) o[id] = qty
  else delete o[id]
  p.o = o
  const first = Object.keys(o)[0] || ''
  p.who = first
  if (me) p.as = me
}

/** Подытог блока: только то, что действительно покупаем. */
export function secSum(rows: Buy[]): number {
  return rows.filter(counted).reduce((s, p) => s + sumOf(p), 0)
}

/** Тот же подытог по ПЛАНОВЫМ ценам — чтобы видеть разницу прямо под блоком. */
export function secPlan(rows: Buy[]): number {
  return rows.filter(counted).reduce((s, p) => s + planSumOf(p), 0)
}

/**
 * Шаблон колонок таблицы закупки. Порядок — как в таблице заказчика:
 * наименование · кол-во · ед. · цена план · цена факт · берём · люди · действия.
 *
 * ⛔ Колонки «Сумма» здесь больше НЕТ. Заказчик 06.08.2026: «Сумма — я не понимаю,
 * что это такое. Бред же: у тебя есть цена плановая, то есть ожидаемая, и цена
 * факт — а сумма-то тут на кой? По сути это оно и есть, это есть цена факт».
 * Считаться она не перестала: `sumOf` цел, `lib/calc.ts` не тронут, а итоги
 * по блоку и по всей закупке стоят внизу — «внизу должен видеть условно как
 * в Excel: сумма факт, сумма план».
 */
export function colsFor(people: number): string {
  return (
    `minmax(11.5rem,1fr) 7rem 4rem 5rem 5rem 3.75rem ` +
    `repeat(${people}, 4.5rem) 6rem`
  )
}
