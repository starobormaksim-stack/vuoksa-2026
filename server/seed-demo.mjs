/**
 * Собрать публичную демо-поездку из боевого листа и положить её на сервер.
 *
 * ─── Зачем ───
 * Заказчику нужна ОДНА ссылка, по которой потенциальный инвестор откроет готовый
 * лист и сможет его потрогать. Боевой лист для этого не годится: он закрыт ключами
 * и полон личного — имена команды, их машины, домашние адреса точек сбора.
 *
 * ─── Что делает ───
 * Берёт живой документ `vuoksa2026`, обезличивает его и кладёт под именем `demo`
 * с СОБСТВЕННЫМИ ключами. Числа, маршрут, списки, расчёты — настоящие: демо должно
 * показывать продукт, а не пустую заготовку.
 *
 * ⛔ Ссылка публичная и без пароля. Всё, что осталось в документе, увидит любой,
 * кому её перешлют, — поэтому обезличивание не «на всякий случай», а обязательный
 * шаг, и в конце стоит ЗАСЛОНКА: если после замен в документе нашлось хоть одно
 * личное слово, скрипт падает и ничего не выкладывает.
 *
 * ─── Как запускать ───
 *   node server/seed-demo.mjs            # собрать и выложить
 *   node server/seed-demo.mjs --dry      # только собрать и проверить, не выкладывая
 *
 * Этим же скриптом демо возвращается в исходный вид, если гость в нём напортил.
 *
 * Ключ владельца берётся из последнего снимка в `backups/` (папка в гит не ходит).
 * Демо-ключи ЗАШИТЫ ниже нарочно: они не секрет, а адрес публичной демонстрации,
 * и от запуска к запуску меняться не должны — иначе разосланная ссылка умрёт.
 */
import { readFileSync, readdirSync } from 'node:fs'

const BASE = 'https://pine-to-pine-api.vercel.app'
const FROM = 'vuoksa2026'
const TO = 'demo'
const DRY = process.argv.includes('--dry')

/* ── кем населяем демо ────────────────────────────────────────────────────── */

/**
 * Имена подобраны так, чтобы склоняться ТОЧНО как настоящие: «Кости» → «Никиты»,
 * «Мише» → «Паше». Иначе замена в свободном тексте («сбор у Кости») оставила бы
 * рваные фразы, а вычитывать триста строк вручную было бы нечем.
 *
 * `id` НЕ меняем: на них держатся все ссылки документа — кто платит, кто везёт,
 * чьи галочки. Смена id обнулила бы половину листа (постулат 4).
 */
const ЛЮДИ = {
  max: {
    name: 'Артём', ini: 'А', slug: 'Artem', key: 'dzt3sb9t',
    car: 'Toyota RAV4 · пассажир', role: 'снаряжение, рыбалка, костровое',
    desc: 'Собирает список, держит связь с базой, отвечает за рыбалку и костровое.',
  },
  kos: {
    name: 'Никита', ini: 'Н', slug: 'Nikita', key: 'mcilqhek',
    car: 'Toyota RAV4 · за рулём', role: 'лодочный мотор 9,9 л.с. — везёт в машине',
    desc: 'За рулём Toyota RAV4. Везёт лодочный мотор 9,9 л.с. Сбор команды — у него.',
  },
  mis: {
    name: 'Паша', ini: 'П', slug: 'Pasha', key: 'mgkg6gcv',
    car: 'Skoda Octavia · за рулём', role: 'костёр, дрова, холодильник', desc: '',
  },
}

/** Замены в свободном тексте. Длинные формы ПЕРЕД короткими: «Макса» до «Макс». */
const СЛОВА = [
  ['Макса', 'Артёма'], ['Макс', 'Артём'],
  ['Кости', 'Никиты'], ['Костя', 'Никита'],
  ['Миши', 'Паши'], ['Миша', 'Паша'],
  ['Жени', 'Лёши'],
  ['Honda Accord', 'Toyota RAV4'], ['Chevrolet Aveo', 'Skoda Octavia'],
]

/**
 * Две точки сбора стоят на жилых адресах — это чужие дома, и в публичной
 * демонстрации им не место. Переносим на общественные места поблизости: форма
 * маршрута сохраняется, а булавка ни на чьём доме больше не стоит.
 */
const ТОЧКИ = {
  rpmshzqhxj: {
    n: 'Сбор команды', addr: 'Дворцовая пл., Санкт-Петербург', lat: 59.9398, lon: 30.3146,
  },
  rpmshzy9t7: {
    n: 'Второй сбор', addr: 'просп. Просвещения, Санкт-Петербург', lat: 60.0517, lon: 30.3336,
  },
  rpmsi0k3au: {
    n: 'Возвращение', addr: 'Дворцовая пл., Санкт-Петербург', lat: 59.9398, lon: 30.3146,
  },
}

/**
 * Заслонка на будущее. Точки маршрута заказчик правит сам, и однажды он снова
 * поставит булавку на чей-нибудь дом — а демо пересобирается из живого листа.
 * Ловим городской адрес с номером дома: улица, проспект или переулок плюс число.
 * Шоссе исключено нарочно — это дорога, а не чей-то подъезд.
 */
const ЖИЛОЙ = /(?:(?:ул|пр|просп|пер|наб|б-р|бул)\.[^,]*,\s*\d+|^\d+,\s*\d+,)/i

/**
 * Шоссе — не подъезд, и Приозерск с деревнями тоже: там стоит лодочная станция
 * и стоянки, а не чьи-то квартиры. Проверяем только городские адреса.
 */
const ГОРОД = /Санкт-Петербург/i
const ДОРОГА = /\sш\.|шоссе/i

/**
 * Чего в демо остаться не должно ни при каких обстоятельствах.
 *
 * ⛔ Личных ключей команды здесь НЕТ и быть не может: этот файл лежит в публичном
 * репозитории. Ключи дописываются на ходу, из снимка (см. `изСнимка()` ниже) —
 * однажды они уже утекли именно через записанный в репозиторий файл.
 */
const ЗАПРЕЩЕНО_СЛОВА = [
  'Макс', 'Костя', 'Кости', 'Миша', 'Миши', 'Жени',
  'Honda', 'Accord', 'Chevrolet', 'Aveo', 'Суздальский', 'Малая Ленинградская',
]

/* ── ключ, которым читаем боевой лист ─────────────────────────────────────── */

function изСнимка() {
  const dir = 'C:/Projects/Вуокса-2026/backups'
  const files = readdirSync(dir).filter((f) => /^prod-.*\.json$/.test(f)).sort()
  if (!files.length) throw new Error('в backups/ нет снимка, а из него берётся ключ')
  const snap = JSON.parse(readFileSync(dir + '/' + files[files.length - 1], 'utf8'))
  const row = Array.isArray(snap) ? snap[0] : snap['0']
  const люди = row.data.people || []
  const хозяин = люди.find((p) => p.perm === 'chief')
  if (!хозяин?.key) throw new Error('в снимке нет ключа владельца')
  return { ключ: хозяин.key, ключиКоманды: люди.map((p) => p.key).filter(Boolean) }
}

const снимок = изСнимка()

/** Слова заслонки плюс настоящие ключи команды — их в демо быть не должно тем более. */
const ЗАПРЕЩЕНО = [...ЗАПРЕЩЕНО_СЛОВА, ...снимок.ключиКоманды]

/* ── сборка ───────────────────────────────────────────────────────────────── */

const r = await fetch(BASE + '/rest/v1/rpc/trip_read', {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify({ p_id: FROM, p_key: снимок.ключ }),
})
if (!r.ok) throw new Error('боевой лист не отдался: HTTP ' + r.status)
const rows = await r.json()
if (!rows.length) throw new Error('боевой лист пуст')

/* Текстовые замены делаем по всему документу разом: имена живут не только
   в `people`, но и в заметках, подписях и комментариях к позициям. */
let текст = JSON.stringify(rows[0].data)
for (const [было, стало] of СЛОВА) текст = текст.split(было).join(стало)
const demo = JSON.parse(текст)

for (const p of demo.people) {
  const кто = ЛЮДИ[p.id]
  if (!кто) throw new Error('в боевом листе появился человек ' + p.id + ' — опиши его в ЛЮДИ')
  Object.assign(p, кто)
  /* Фотографий в демо нет вовсе: лица живых людей в публичную ссылку не уходят. */
  delete p.photo
}

for (const t of demo.route) {
  const чинить = ТОЧКИ[t.i]
  if (чинить) Object.assign(t, чинить)
}

demo.trip.title = 'ВУОКСА · 2026 · ДЕМО'
demo.author = ЛЮДИ.max.name
demo.me = 'max'

/* ── заслонка ─────────────────────────────────────────────────────────────── */

const итог = JSON.stringify(demo)
/* Картинки из проверки убираем: в base64 случайно встречается любое сочетание
   букв, и заслонка срабатывала бы на пустом месте. */
const без = итог.replace(/"data:image[^"]*"/g, '""')
const остатки = ЗАПРЕЩЕНО.filter((w) => без.includes(w))
if (остатки.length) {
  console.error('⛔ В демо осталось личное: ' + остатки.join(', '))
  console.error('   Ничего не выложено. Допиши замену и повтори.')
  process.exit(1)
}

const жилые = [...demo.route, ...(demo.trip.places || [])]
  .filter((t) => {
    const a = String(t.addr || '')
    return ГОРОД.test(a) && ЖИЛОЙ.test(a) && !ДОРОГА.test(a)
  })
if (жилые.length) {
  console.error('⛔ В маршруте демо остались городские адреса с номером дома:')
  for (const t of жилые) console.error('   ' + t.i + ' · ' + t.n + ' · ' + t.addr)
  console.error('   Это может быть чей-то дом. Опиши их в ТОЧКИ и повтори.')
  process.exit(1)
}

console.log('адреса маршрута, которые уедут в демо:')
for (const t of demo.route) console.log('   ' + (t.n || '—').padEnd(18) + ' · ' + (t.addr || '—'))

console.log(
  'демо собрано:', итог.length, 'байт · людей', demo.people.length,
  '· точек маршрута', demo.route.length,
)
console.log('команда:', demo.people.map((p) => p.name + ' (' + p.slug + ', ' + p.perm + ')').join(' · '))
console.log('личного не осталось: проверено по', ЗАПРЕЩЕНО.length, 'словам')

if (DRY) {
  console.log('')
  console.log('--dry: на сервер ничего не отправлено')
  process.exit(0)
}

/* ── выкладка ─────────────────────────────────────────────────────────────── */

const stamp = new Date().toISOString()
const было = await fetch(BASE + '/rest/v1/rpc/trip_read', {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify({ p_id: TO, p_key: ЛЮДИ.max.key }),
})
const прежние = было.ok ? await было.json() : []
const seen = прежние.length ? прежние[0].updated_at : null

const w = await fetch(BASE + '/rest/v1/rpc/trip_write', {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify({
    p_trip: TO, p_key: ЛЮДИ.max.key, p_data: demo,
    p_seen: seen, p_stamp: stamp, p_author: ЛЮДИ.max.name,
  }),
})
console.log('запись:', w.status, (await w.text()).slice(0, 120))

await fetch(BASE + '/rest/v1/trip_pings', {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify([{ trip_id: TO, updated_at: stamp, author: ЛЮДИ.max.name }]),
})

console.log('')
console.log('ссылка для показа:')
console.log('https://pine-to-pine.com/?trip=' + TO + '&u=' + ЛЮДИ.max.slug + '&k=' + ЛЮДИ.max.key)
